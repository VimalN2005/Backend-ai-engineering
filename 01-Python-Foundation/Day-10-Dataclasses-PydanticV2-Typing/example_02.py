# SIMULATION & VERIFICATION RUNNER
# =====================================================================
def run_simulation() -> None:
    logger.info("Initializing ToolExecutionEngine...")
    engine = ToolExecutionEngine()

    # 1. Export OpenAPI/JSON Schema for LLM Function Calling
    tool_schemas = engine.export_openai_tools()
    print("=" * 65)
    print("1. GENERATED OPENAI / GEMINI FUNCTION CALLING SCHEMA:")
    print("=" * 65)
    print(json.dumps(tool_schemas[0], indent=2))

    # 2. Scenario A: Valid LLM Tool Call
    print("\n" + "=" * 65)
    print("2. SCENARIO A: VALID DATABASE QUERY TOOL CALL")
    print("=" * 65)
    valid_args = json.dumps(
        {
            "query": "SELECT user_id, sum(amount) FROM transactions GROUP BY user_id LIMIT 10",
            "database_target": "analytics_replica",
            "timeout_seconds": 10.0,
        }
    )
    res_a = engine.validate_and_dispatch("execute_database_query", valid_args)
    print(f"[*] Response Status: success={res_a.success}")
    print(f"[*] Response Payload: {res_a.data}")

    # 3. Scenario B: Malicious / Dangerous LLM SQL Injection Attempt
    print("\n" + "=" * 65)
    print("3. SCENARIO B: SECURITY VIOLATION INTERCEPTION")
    print("=" * 65)
    malicious_args = json.dumps(
        {
            "query": "DELETE FROM users WHERE is_active = false",
            "database_target": "users_replica",
            "timeout_seconds": 5.0,
        }
    )
    res_b = engine.validate_and_dispatch("execute_database_query", malicious_args)
    print(f"[*] Response Status: success={res_b.success}")
    print(f"[*] Security Errors Intercepted: {res_b.errors}")

    # 4. Scenario C: Hallucinated Field & Out-Of-Bounds Parameters
    print("\n" + "=" * 65)
    print("4. SCENARIO C: SELF-CORRECTION DIAGNOSTICS")
    print("=" * 65)
    hallucinated_args = json.dumps(
        {
            "query_text": "AI",          # Too short (min_length=3)
            "top_k": 100,                # Out of bounds (le=50)
            "similarity_threshold": 1.5, # Out of bounds (le=1.0)
            "collection_name": "unknown_collection", # Invalid literal
            "hallucinated_key": "hallucinated_value", # Extra forbidden field
        }
    )
    res_c = engine.validate_and_dispatch("query_vector_index", hallucinated_args)
    print(f"[*] Response Status: success={res_c.success}")
    print("[*] Diagnostic Errors generated for LLM Self-Correction Prompt:")
    for err in res_c.errors:
        print(f"    - Field: {err['field']} | Input: {err.get('input')} | Issue: {err['message']}")


if __name__ == "__main__":
    run_simulation()
